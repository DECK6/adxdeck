import hashlib, json, re, unittest, zipfile
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
SITE = ROOT / 'ontology/study'

class WeekFourRelease(unittest.TestCase):
    def test_google_drive_downloads_and_metadata(self):
        manifest=json.loads((SITE/'downloads/week4/manifest.json').read_text())
        text=(SITE/'week4.html').read_text()
        for entry in [*manifest['packages'].values(),manifest['operating_kit'],manifest['akm_skills']]:
            self.assertTrue(entry['download_url'].startswith('https://drive.google.com/file/d/'))
            self.assertIn(entry['download_url'],text)
            self.assertRegex(entry['sha256'],r'^[0-9a-f]{64}$')
        self.assertNotRegex(text,r'href="[^"\s]+\.zip"')

    def test_both_complete_packages_have_identical_records(self):
        manifest=json.loads((SITE/'downloads/week4/manifest.json').read_text())
        if not all((SITE/'downloads'/v['file']).exists() for v in manifest['packages'].values()):
            self.skipTest('Local ZIPs are generated by package-week4.py and hosted on Google Drive.')
        hashes=[]
        for variant in ['plain','ontology']:
            entry=manifest['packages'][variant]
            path=SITE/'downloads'/entry['file']
            self.assertEqual(hashlib.sha256(path.read_bytes()).hexdigest(),entry['sha256'])
            self.assertLess(path.stat().st_size,100*1024**2)
            with zipfile.ZipFile(path) as z:
                self.assertIsNone(z.testzip())
                records=z.read(f'species-{variant}/{variant}/records.jsonl')
                self.assertEqual(len(records.splitlines()),62604)
                hashes.append(hashlib.sha256(records).hexdigest())
                for f in ['START-HERE.md','query_local.py','PROVENANCE.md']:
                    self.assertIn(f'species-{variant}/{f}',z.namelist())
        self.assertEqual(hashes,[manifest['document_sha256']]*2)

    def test_course_and_local_links(self):
        from html.parser import HTMLParser
        from urllib.parse import urlsplit,unquote
        class Links(HTMLParser):
            def __init__(self): super().__init__(); self.ids=[];self.links=[]
            def handle_starttag(self,tag,attrs):
                a=dict(attrs)
                if 'id' in a:self.ids.append(a['id'])
                for k in ['href','src','data-src']:
                    if a.get(k):self.links.append(a[k])
        path=SITE/'week4.html';text=path.read_text();p=Links();p.feed(text)
        self.assertEqual(len(p.ids),len(set(p.ids)))
        for url in p.links:
            u=urlsplit(url)
            if u.scheme or u.netloc:continue
            dest=ROOT/unquote(u.path).lstrip('/') if u.path.startswith('/') else path.parent/unquote(u.path)
            if not u.path:dest=path
            self.assertTrue(dest.exists(),url)
            if u.fragment and dest==path:self.assertIn(u.fragment,p.ids,url)
        for word in ['내 지식을 계속 관리해 주는 에이전트 만들기','복리','자가증식','RDF','OWL 2','최종 발표','18/18','41.9','22.5','유보']:
            self.assertIn(word,text)
        self.assertNotRegex(text,r'<iframe[^>]+\ssrc=')

    def test_public_results_preserve_all_runs_without_machine_context(self):
        base=SITE/'week4-species'
        for folder,count in [(base,48),(base/'large-scale',36)]:
            runs=list((folder/'runs').glob('*.json'))
            self.assertEqual(len(runs),count)
            for p in runs:
                raw=p.read_text();run=json.loads(raw)
                self.assertNotIn('/Volumes/',raw);self.assertNotIn('invocation_command',run);self.assertNotIn('thread_id',run)
                self.assertIn('answer',run);self.assertIn('trace',run)
        summary=json.loads((base/'large-scale/summary.json').read_text())
        self.assertEqual(summary['stats']['plain']['all']['unknown'],18)
        self.assertEqual(summary['stats']['ontology']['all']['correct'],18)

if __name__=='__main__':unittest.main()
